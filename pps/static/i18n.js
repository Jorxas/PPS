  let lang = "de";
  try {
    const wanted = new URLSearchParams(location.search).get("lang");
    if (LANGS.includes(wanted)) lang = wanted;
  } catch (_) {}

  const fill = (text, params) =>
    params ? text.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : text;
  function tx(key, params) {
    const entry = K[key];
    if (!entry) return key;
    return fill(entry[LANGS.indexOf(lang)] ?? entry[0], params);
  }
  const locale = () => LOCALES[lang];
  // Zahlen und Zeiten im Format der gewählten Sprache (de-DE: 1.234,5; fr-FR: 1 234,5).
  const fixed = (n, digits) => Number(n).toLocaleString(locale(), { minimumFractionDigits: digits, maximumFractionDigits: digits });
  const numl = (n, max = 1) => Number(n).toLocaleString(locale(), { maximumFractionDigits: max });
  const dateTime = (seconds) => new Date(seconds * 1000).toLocaleString(locale());
  const plural = (n) => ((lang === "fr" ? n > 1 : n !== 1) ? "many" : "one");
  const langName = (code) => (K["lang." + code] ? tx("lang." + code) : code);

  function applyStatic() {
    document.documentElement.lang = lang;
    for (const [attribute, target] of [["data-i18n", null], ["data-i18n-ph", "placeholder"], ["data-i18n-aria", "aria-label"], ["data-i18n-title", "title"]])
      for (const element of document.querySelectorAll("[" + attribute + "]")) {
        const text = tx(element.getAttribute(attribute), element.dataset.engine ? { engine: element.dataset.engine } : undefined);
        if (target) element.setAttribute(target, text);
        else element.textContent = text;
      }
  }
  function setLang(next) {
    if (!LANGS.includes(next) || next === lang) return;
    lang = next;
    try {
      const url = new URL(location.href);
      if (lang === "de") url.searchParams.delete("lang");
      else url.searchParams.set("lang", lang);
      history.replaceState(null, "", url.pathname + url.search + url.hash);
    } catch (_) {}
    applyStatic();
    document.dispatchEvent(new Event("pps-lang"));
  }
  Object.assign(window, { tx, fixed, numl, dateTime, plural, langName, setLang, getLang: () => lang, ppsLocale: locale, ppsDictionary: K });
  applyStatic();
